acc={}
for s in secs:
    if not s.startswith('## '): continue
    h=s.split('\n',1)[0][3:]
    for k,v in M.items():
        if h.startswith(k):
            for f in v: acc.setdefault(f,[]).append(s.replace('## ','### ',1))
            break
    else: print('UNMAPPED',h)
